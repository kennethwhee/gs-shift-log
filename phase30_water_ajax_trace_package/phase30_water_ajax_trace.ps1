/* =========================================================
  [PHASE3.0 WATER AJAX TRACE]

  Temporary diagnostic only.
  Captures POST /ajax/data traffic generated by one Water query.

  Logged:
  - command
  - tossdata/select payload
  - HTTP status
  - JSON result count / first rows

  No cookies, authorization headers, passwords, or session values
  are logged.
========================================================= */
function createPhase30WaterAjaxTrace(
  page,
  targetDate
) {
  const pendingResponses =
    new Set();


  const getRequestInfo =
    request => {
      const postData =
        String(
          request.postData() ||
          ""
        );


      const parameters =
        new URLSearchParams(
          postData
        );


      return {
        command:
          parameters.get(
            "cmd"
          ) ||
          parameters.get(
            "CMD"
          ) ||
          "",

        tossdata:
          parameters.get(
            "tossdata"
          ) ||
          parameters.get(
            "TOSSDATA"
          ) ||
          ""
      };
    };


  const isTargetRequest =
    request => {
      return (
        String(
          request.method() ||
          ""
        ).toUpperCase() ===
          "POST" &&
        String(
          request.url() ||
          ""
        ).includes(
          "/ajax/data"
        )
      );
    };


  const compactText =
    (
      value,
      limit =
        8000
    ) => {
      const text =
        String(
          value ??
          ""
        )
          .replace(
            /\s+/g,
            " "
          )
          .trim();


      return text.length >
        limit
        ? (
            text.slice(
              0,
              limit
            ) +
            "...[TRUNCATED]"
          )
        : text;
    };


  const summarizeResponse =
    responseText => {
      const normalized =
        String(
          responseText ||
          ""
        ).trim();


      if (
        !normalized
      ) {
        return {
          format:
            "empty"
        };
      }


      try {
        const parsed =
          JSON.parse(
            normalized
          );


        const result =
          parsed?.result;


        return {
          format:
            "json",

          keys:
            parsed &&
            typeof parsed ===
              "object"
              ? Object.keys(
                  parsed
                )
              : [],

          resultCount:
            Array.isArray(
              result
            )
              ? result.length
              : null,

          resultPreview:
            Array.isArray(
              result
            )
              ? result.slice(
                  0,
                  6
                )
              : result
        };

      } catch {
        return {
          format:
            "text",

          preview:
            compactText(
              normalized,
              4000
            )
        };
      }
    };


  const handleRequest =
    request => {
      if (
        !isTargetRequest(
          request
        )
      ) {
        return;
      }


      const {
        command,
        tossdata
      } =
        getRequestInfo(
          request
        );


      console.log(
        "[PHASE3.0 WATER AJAX TRACE] REQUEST " +
        JSON.stringify({
          targetDate,
          command,
          tossdata:
            compactText(
              tossdata,
              8000
            )
        })
      );
    };


  const handleResponse =
    response => {
      const request =
        response.request();


      if (
        !isTargetRequest(
          request
        )
      ) {
        return;
      }


      const task =
        (
          async () => {
            const {
              command,
              tossdata
            } =
              getRequestInfo(
                request
              );


            const responseText =
              await response
                .text()
                .catch(
                  error => {
                    return (
                      "[response read error] " +
                      (
                        error instanceof
                          Error
                          ? error.message
                          : String(
                              error ||
                              ""
                            )
                      )
                    );
                  }
                );


            console.log(
              "[PHASE3.0 WATER AJAX TRACE] RESPONSE " +
              JSON.stringify({
                targetDate,
                command,
                tossdata:
                  compactText(
                    tossdata,
                    8000
                  ),
                status:
                  response.status(),
                summary:
                  summarizeResponse(
                    responseText
                  )
              })
            );
          }
        )();


      pendingResponses.add(
        task
      );


      task.finally(
        () => {
          pendingResponses.delete(
            task
          );
        }
      );
    };


  return {
    start() {
      page.on(
        "request",
        handleRequest
      );


      page.on(
        "response",
        handleResponse
      );


      console.log(
        `[PHASE3.0 WATER AJAX TRACE] START ${targetDate}`
      );
    },


    async stop() {
      page.off(
        "request",
        handleRequest
      );


      page.off(
        "response",
        handleResponse
      );


      if (
        pendingResponses.size >
          0
      ) {
        await Promise.allSettled(
          [
            ...pendingResponses
          ]
        );
      }


      console.log(
        `[PHASE3.0 WATER AJAX TRACE] STOP ${targetDate}`
      );
    }
  };
}


